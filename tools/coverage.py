"""Generate native ABI comparisons and a checked public user-mode coverage inventory."""
from pathlib import Path
import re,json,hashlib,sys
root=Path(__file__).resolve().parent.parent
crate=root/'crates/winxdp-sys'
s=(crate/'src/bindings.rs').read_text()
types=(root/'tools/types.txt').read_text().splitlines()
constants=[n for n in (root/'tools/constants.txt').read_text().splitlines() if re.search(r'pub const '+n+r'\b',s)]
functions=json.loads((root/'tools/functions.json').read_text())
cpp=['#include "base.h"','#include <stddef.h>','size_t wx_abi(unsigned id) { switch (id) {']
tests=['#![cfg(windows)]','#![allow(clippy::unnecessary_cast)]','use winxdp_sys::*;','unsafe extern "C" {fn wx_abi(id:u32)->usize;}','#[test] fn native_layouts_and_constants() {']
index=0
for name in types:
 if not (re.search(r'pub type '+name+r'\b',s) or re.search(r'pub use [^;]+ as '+name+r';',s)):continue
 if name=='xdp_hook_t':continue
 for c,r in [(f'sizeof({name})',f'std::mem::size_of::<{name}>()'),(f'__alignof({name})',f'std::mem::align_of::<{name}>()')]:
  cpp.append(f'case {index}: return {c};');tests.append(f'assert_eq!(unsafe {{wx_abi({index})}}, {r}, "{name}");');index+=1
 alias=re.search(r'pub type '+name+r' = (\w+);',s)
 body=re.search(r'pub (?:struct|union) '+alias[1]+r'\s*\{(.*?)\n\}',s,re.S) if alias else None
 if body:
  for field in re.findall(r'pub (\w+):',body[1]):
   if field.startswith('_'):continue
   cpp.append(f'case {index}: return offsetof({name}, {field});');tests.append(f'assert_eq!(unsafe {{wx_abi({index})}},std::mem::offset_of!({name},{field}),"{name}.{field}");');index+=1
for name in constants:
 if name.endswith('_NAME'):continue
 cpp.append(f'case {index}: return (size_t)(UINT32)({name});');tests.append(f'assert_eq!(unsafe {{wx_abi({index})}}, {name} as u32 as usize,"{name}");');index+=1
cpp+=['default: return (size_t)-1;','} }'];tests+=['}']
(crate/'native/abi.c').write_text('\n'.join(cpp)+'\n')
(crate/'tests').mkdir(exist_ok=True);(crate/'tests/abi.rs').write_text('\n'.join(tests)+'\n')
headers=[p for p in (crate/'vendor').rglob('*.h') if 'details' not in p.parts and not p.name.endswith('_v1.h')]
rows=[]
for name,kind in [(n,'type') for n in types]+[(n,'constant') for n in constants]+[(f[1],'function') for f in functions]:
 paths=[p.relative_to(crate/'vendor').as_posix() for p in headers if re.search(r'\b'+name+r'\b',p.read_text())]
 legacy=name in ['XdpCreateProgram'] or any(p=='xdp/program.h' for p in paths)
 rows.append({'symbol':name,'kind':kind,'header':paths[0] if paths else 'native/base.h','sys':name,'high_level':('Socket' if name in ['XskCreate','XskBind','XskActivate','XskNotifySocket','XskSetSockopt','XskGetSockopt'] else 'raw ABI only'),'status':'deprecated' if legacy else 'implemented','test':('compile-time signature' if name=='xdp_hook_t' else 'native_layouts_and_constants') if kind!='function' else 'native link / hardware opt-in','notes':'experimental' if any('experimental' in p for p in paths) else ''})
for name in ['XDP_STATUS','XDP_FAILED','XDP_SUCCEEDED']:
 rows.append({'symbol':name,'kind':'macro-adapter','header':'xdp/status.h','sys':name,'high_level':'status handling','status':'implemented','test':'status_semantics','notes':'user-mode HRESULT semantics'})
for name,header,reason in [('XdpRegisterDriverStartCallback','xdpapi.h','kernel-only'),('XdpDeregisterDriverStartCallback','xdpapi.h','kernel-only'),('XdpOpenApi','xdp/xdpapi_v1.h','deprecated DLL dispatch ABI'),('XDP_FRAME_FRAGMENT','xdp/framefragment.h','kernel DDI; no XSK fragment socket option')]:
 rows.append({'symbol':name,'kind':'excluded','header':header,'sys':None,'high_level':None,'status':'not-applicable','test':None,'notes':reason})
(root/'docs/api-coverage.json').write_text(json.dumps(rows,indent=2)+'\n')
md='# Public user-mode API coverage\n\nGenerated by `python tools/coverage.py`; pinned v1.4.0 / API v3.\nTypes include enum aliases and bitfield accessors. C bridge compiles every function.\nHardware execution is **not** implied by implemented status.\n\n| Symbol | Header | sys | High-level | Status | Test | Notes |\n|---|---|---|---|---|---|---|\n'
for r in rows:md+='| '+' | '.join(str(r[k] or '-') for k in ['symbol','header','sys','high_level','status','test','notes'])+' |\n'
(root/'docs/api-coverage.md').write_text(md)
print(f'{index} native ABI assertions; {len(rows)} inventory rows')
